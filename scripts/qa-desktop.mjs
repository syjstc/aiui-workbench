import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { _electron as electron } from 'playwright';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { connect } from '../core/client.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const home=path.join(root,'.local'), output=path.join(root,'output/qa');
process.env.AIUI_WORKBENCH_HOME=home;await fs.mkdir(output,{recursive:true});
const client=await connect(home);
const project=await client.call('aiui_project_import',{directory:path.resolve(root,'examples/hello-aiui')},'qa');
const app=await electron.launch({args:[root],cwd:root,env:{...process.env,AIUI_WORKBENCH_HOME:home,ELECTRON_RUN_AS_NODE:''}});
const page=await app.firstWindow();
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')process.stderr.write('UI '+m.text()+'\n');});
await page.getByRole('heading',{name:'把想法，带到眼前。'}).waitFor();
await page.getByRole('heading',{name:project.name,exact:true}).waitFor();
await page.screenshot({path:path.join(output,'01-project-library.png')});
await page.getByRole('heading',{name:project.name,exact:true}).click();
await page.frameLocator('iframe').locator('#screen').waitFor({state:'visible',timeout:60000});
await page.getByText('预览运行中',{exact:true}).waitFor({timeout:60000});
await page.frameLocator('iframe').locator('#status').waitFor({state:'hidden',timeout:60000});
await page.screenshot({path:path.join(output,'02-hello-aiui-menu.png')});
const preview=(await client.call('aiui_status')).previews.find(p=>p.projectId===project.id);
if(!preview)throw new Error('示例预览未创建');
process.stdout.write(JSON.stringify({app:'ready',project:project.name,session:preview.id,preview:preview.status})+'\n');
const transport=new StdioClientTransport({command:process.execPath,args:[path.join(root,'mcp/server.mjs')],env:{...process.env,AIUI_WORKBENCH_HOME:home}});
const mcp=new Client({name:'workbench-qa',version:'1.0.0'});await mcp.connect(transport);
const tools=await mcp.listTools();
const result=await mcp.callTool({name:'aiui_preview_capture',arguments:{sessionId:preview.id}});
if(result.isError||result.content[0].type!=='image')throw new Error('MCP 截图失败');
await fs.writeFile(path.join(output,'03-mcp-capture.png'),Buffer.from(result.content[0].data,'base64'));
await fs.writeFile(path.join(output,'initial-report.json'),JSON.stringify({projectId:project.id,sessionId:preview.id,tools:tools.tools.map(t=>t.name),errors,logs:await client.call('aiui_preview_logs',{sessionId:preview.id,limit:40})},null,2));
await mcp.close();
if(process.env.AIUI_QA_KEEP_OPEN!=='1')await app.close();
else { process.stdout.write('QA desktop remains open\n'); await new Promise(()=>{}); }
